#!/bin/sh
# Entrypoint of the Hermes agent service — calliopa-app's entrypoint
# (CA_0022_005, CA_0022_009, CA_0022_010, CA_0026_001), carried into this
# stack with the kernel toolset as the agent's one toolset (BO_0207_006).
# BO_0200_007 BO_0200_008
#
# Everything Hermes needs that is not in the image is assembled here at start:
# the API-server .env, the agent's credentials for both Calliopa tool
# surfaces, and the configuration that says which runtime is reasoning. All of
# it lands on the data volume rather than in the image, because a baked
# credential cannot be rotated and a baked runtime cannot be chosen.
#
# The gateway is then supervised: when the settings surface writes new agent
# configuration to the shared volume, the configuration is regenerated and the
# gateway restarted. That is why a runtime change costs a restart and not a
# rebuild.
#
# No secret is ever echoed. Values are read into files with a restrictive
# umask and referred to by path afterwards.
set -eu

HERMES_HOME="${HERMES_HOME:-/var/lib/hermes}"
AGENT_CONFIG_DIR="${CALLIOPA_AGENT_CONFIG_DIR:-/var/lib/calliopa/agent-config}"
RUNTIME_ENV="$AGENT_CONFIG_DIR/runtime.env"
PROVIDER_ENV="$AGENT_CONFIG_DIR/provider.env"
CLAUDE_ENV="$AGENT_CONFIG_DIR/claude.env"
KERNEL_BEARER_FILE="$HERMES_HOME/kernel-bearer"
# The kernel toolset, the agent's one toolset since BO_0207_006: CCGW reads
# and writes, the document tools, and the run-scoped workspace tools. Only
# bridge-started runs hold its per-run binding. The shell's own MCP surface
# and the cak_ token that reached it are retired (BO_0207_015).
KERNEL_TOOLS_URL="${CALLIOPA_KERNEL_TOOLS_URL:-http://kernel:8090/__kernel/agent-tools}"

# Secrets are files or environment, never arguments: an argument is visible in
# the process table to anything else in the container.
secret() {
  file_var="$1"
  value_var="$2"
  eval "file=\${$file_var:-}"
  eval "value=\${$value_var:-}"
  if [ -n "$file" ] && [ -f "$file" ]; then
    cat "$file"
  else
    printf '%s' "$value"
  fi
}

umask 077
mkdir -p "$HERMES_HOME" "$AGENT_CONFIG_DIR"

# Subscription credential homes live on the volume, so signing in survives a
# restart and a rebuild. This is also why losing the volume means signing in
# again, which is the accepted cost of keeping them where their tooling looks.
HOME="$HERMES_HOME"
export HOME

# The API server bearer: the file this stack's bootstrap generates
# (CALLIOPA_HERMES_API_SECRET_FILE), or the shell's own variable names.
api_key="$(secret CALLIOPA_HERMES_API_SECRET_FILE CALLIOPA_HERMES_API_KEY)"
if [ -z "$api_key" ]; then
  api_key="$(secret CALLIOPA_HERMES_API_KEY_FILE CALLIOPA_HERMES_API_KEY)"
fi
if [ -z "$api_key" ]; then
  echo "refusing to start: no API server key was provided" >&2
  exit 1
fi

cat > "$HERMES_HOME/.env" <<ENVEOF
API_SERVER_ENABLED=true
API_SERVER_KEY=$api_key
API_SERVER_HOST=${API_SERVER_HOST:-0.0.0.0}
API_SERVER_PORT=${API_SERVER_PORT:-8642}
ENVEOF
unset api_key

# A tools-token file an earlier start wrote for the shell's retired surface
# is removed, so nothing on the volume names a credential nothing accepts.
rm -f "$HERMES_HOME/tools-token"

# The kernel toolset's bearer, generated by this stack's bootstrap.
kernel_bearer="$(secret CALLIOPA_AGENT_TOOLS_BEARER_FILE CALLIOPA_AGENT_TOOLS_BEARER)"
if [ -n "$kernel_bearer" ]; then
  printf '%s\n' "$kernel_bearer" > "$KERNEL_BEARER_FILE"
else
  rm -f "$KERNEL_BEARER_FILE"
fi
unset kernel_bearer

# The Codex worker's permission profile. These two values are the confinement,
# and they are fixed here rather than read from anywhere: the settings surface
# writes agent configuration onto a shared volume, and configuration a remote
# surface can write must not be able to widen the sandbox. Rewriting them on
# every start is what makes that true regardless of what else is on the volume.
#
# Never the full-bypass combination: `approval_policy = "never"` with
# `sandbox_mode = "danger-full-access"` would be an agent with a shell on the
# container, answerable to nobody. The container is the outer boundary, and the
# profile is the gate inside it.
write_codex_profile() {
  mkdir -p "$HOME/.codex"
  python3 - <<'PYEOF'
import os
import re

path = os.path.join(os.environ["HOME"], ".codex", "config.toml")
content = open(path).read() if os.path.exists(path) else ""
for key, value in (("approval_policy", '"never"'), ("sandbox_mode", '"workspace-write"')):
    if re.search(rf"^{key}\s*=", content, re.M):
        content = re.sub(rf"^{key}\s*=.*$", f"{key} = {value}", content, flags=re.M)
    else:
        content = f"{key} = {value}\n" + content
open(path, "w").write(content)
PYEOF
}

# The codex runtime brings Codex's own tool surface, so each toolset has to be
# registered there as well as with Hermes. `--bearer-token-env-var` is the
# whole point: Codex stores the variable's *name* in config.toml and reads the
# value from the environment at call time, so the credential never lands in a
# file Codex owns.
#
# Whether the registration succeeded is remembered rather than only warned
# about: the settings surface and the kernel bridge are never passed the
# credential, so what they can say about the agent's tools is only what this
# start stamped.
kernel_toolset_registered="false"

# register_codex_server NAME URL TOKEN_FILE ENV_VAR -> "true" | "false"
register_codex_server() {
  name="$1"; url="$2"; token_file="$3"; env_var="$4"
  if [ ! -s "$token_file" ]; then
    # Codex keeps its configuration on the volume, so an entry left behind
    # would outlive the credential it names and the stamp would be describing
    # a registration that is no longer backed by anything.
    codex mcp remove "$name" >/dev/null 2>&1 || true
    printf 'false'
    return 0
  fi
  eval "$env_var=\"\$(cat \"$token_file\")\""
  eval "export $env_var"
  codex mcp remove "$name" >/dev/null 2>&1 || true
  if ! codex mcp add "$name" --url "$url" --bearer-token-env-var "$env_var" >/dev/null 2>&1; then
    echo "warning: codex mcp add $name failed; the codex runtime will lack those tools"
    printf 'false'
    return 0
  fi
  printf 'true'
}

# write_config regenerates Hermes's configuration from the current agent
# configuration. The runtime selection chooses the model *under* Hermes — the
# conversation loop's own LLM — not a delegated worker.
write_config() {
  runtime="${CALLIOPA_AGENT_RUNTIME:-codex}"
  {
    # The toolset Hermes reaches Calliopa through. The release interpolates
    # nothing in this file, so the bearer is literal here; the file lives on
    # the volume under a restrictive umask and never in the image. Codex's own
    # copy below takes the value through the environment instead.
    if [ -s "$KERNEL_BEARER_FILE" ]; then
      printf 'mcp_servers:\n'
      printf '  calliopa-kernel:\n    url: %s\n    headers:\n      Authorization: Bearer %s\n' \
        "$KERNEL_TOOLS_URL" "$(cat "$KERNEL_BEARER_FILE")"
    fi
    case "$runtime" in
      codex)
        # The ChatGPT subscription is the reasoning credential: no model API
        # key is involved, and the app-server subprocess authenticates from the
        # Codex CLI's own home on this volume.
        printf 'model:\n  default: "%s"\n  provider: openai-codex\n  openai_runtime: codex_app_server\n' \
          "${CALLIOPA_CODEX_MODEL:-gpt-5.5}"
        # A gateway context has no UI for an approval request, so the choice is
        # between failing closed on every tool call and deferring to a real
        # sandbox profile. Hermes defers; Codex's own profile below is the
        # deny-by-default gate. The quoting keeps YAML from reading the value
        # as a boolean.
        printf 'approvals:\n  mode: "off"\n'
        ;;
      *)
        # An explicit API-key model as controller (the `provider` and
        # `claude-code` selections of the kernel bridge). Kept as a
        # configuration path and normally unconfigured; Calliopa ships with no
        # model API key.
        if [ -n "${CALLIOPA_AGENT_MODEL:-}" ]; then
          printf 'model: "%s"\n' "$CALLIOPA_AGENT_MODEL"
        fi
        ;;
    esac
  } > "$HERMES_HOME/config.yaml"

  write_codex_profile
  # An entry an earlier start registered for the shell's retired surface is
  # removed the way a lost credential's would be.
  codex mcp remove calliopa >/dev/null 2>&1 || true
  kernel_toolset_registered="$(register_codex_server calliopa-kernel "$KERNEL_TOOLS_URL" "$KERNEL_BEARER_FILE" CALLIOPA_AGENT_TOOLS_BEARER)"

  # The active runtime and the toolset this start assembled are stamped as
  # fact for the surfaces that report them, never inferred from what happened
  # to answer. The credential and the registration are stamped apart because
  # they ask different things of the reader: a credential the bootstrap did
  # not generate is an install that did not run, while a registration that
  # failed with the credential in hand is the agent's own log to explain.
  if [ -s "$KERNEL_BEARER_FILE" ]; then kernel_credential="true"; else kernel_credential="false"; fi
  printf '{"runtime": "%s", "kernelCredential": %s, "kernelToolset": %s}\n' \
    "$runtime" "$kernel_credential" "$kernel_toolset_registered" \
    > "$AGENT_CONFIG_DIR/active-runtime.json"
  echo "agent configuration written for runtime $runtime (kernel toolset: $kernel_toolset_registered)"
}

# The mtimes of the files the settings surface and the kernel bridge write.
# Comparing them is what makes a configuration change observable without
# watching tools the image lacks.
stamp() {
  for file in "$RUNTIME_ENV" "$PROVIDER_ENV" "$CLAUDE_ENV"; do
    if [ -f "$file" ]; then
      stat -c %Y "$file" 2>/dev/null || echo unreadable
    else
      echo none
    fi
  done
}

# The login broker serves the subscription sign-ins over the shared volume and
# keeps the runtime probe current, so signing in is something the settings
# surface can offer rather than something a human does at a terminal on the
# machine.
python3 /usr/local/bin/hermes-login-broker &
broker=$!

pid=""
shutdown() {
  kill "$broker" 2>/dev/null || true
  if [ -n "$pid" ]; then
    kill "$pid" 2>/dev/null || true
    wait "$pid" 2>/dev/null || true
  fi
  exit 0
}
trap shutdown TERM INT

while true; do
  current="$(stamp)"
  # Agent configuration written by the settings surface (runtime.env), the
  # kernel bridge's provider selection (provider.env) and the login broker's
  # captured Claude token (claude.env): sourced into the gateway's environment
  # rather than into the image.
  for file in "$PROVIDER_ENV" "$RUNTIME_ENV" "$CLAUDE_ENV"; do
    if [ -f "$file" ]; then
      set -a
      # shellcheck disable=SC1090
      . "$file"
      set +a
    fi
  done
  write_config

  hermes gateway run &
  pid=$!
  while kill -0 "$pid" 2>/dev/null; do
    sleep 2
    if [ "$(stamp)" != "$current" ]; then
      echo "agent configuration changed; restarting the gateway"
      kill "$pid" 2>/dev/null || true
      break
    fi
  done
  wait "$pid" 2>/dev/null || true
  pid=""
  sleep 1
done
